def protection_for(level_key: str | None) -> list[dict]:
    """วิธีป้องกันตัวของระดับคุณภาพอากาศที่กำหนด

    คืนรายการว่างเมื่อไม่รู้ระดับ ให้หน้าเว็บซ่อนแถบไปเลย
    ดีกว่าขึ้นคำแนะนำกลาง ๆ ที่ไม่ตรงกับค่าที่วัดได้จริง
    """
    return list(_PROTECTION.get(level_key or "", []))


def advice_for(level_key: str | None) -> list[dict]:
    """คำแนะนำของทุกกลุ่มเสี่ยง ณ ระดับคุณภาพอากาศที่กำหนด"""
    table = _ADVICE.get(level_key or "", {})
    return [
        {
            "key": group.key,
            "label_th": group.label_th,
            "detail_th": group.detail_th,
            "sensitive": group.sensitive,
            "advice_th": table.get(group.key, "ยังไม่มีข้อมูลเพียงพอสำหรับให้คำแนะนำ"),
        }
        for group in RISK_GROUPS
    ]


def compare_standards(pm25: float | None) -> dict:
    """เทียบค่าที่วัดได้กับมาตรฐานไทยและค่าแนะนำขององค์การอนามัยโลก"""
    if pm25 is None:
        return {
            "pm25": None,
            "thai_standard": THAI_STANDARD_PM25,
            "who_guideline": WHO_GUIDELINE_PM25,
            "over_thai_standard": False,
            "over_who_guideline": False,
            "times_who": None,
        }
    return {
        "pm25": pm25,
        "thai_standard": THAI_STANDARD_PM25,
        "who_guideline": WHO_GUIDELINE_PM25,
        "over_thai_standard": pm25 > THAI_STANDARD_PM25,
        "over_who_guideline": pm25 > WHO_GUIDELINE_PM25,
        "times_who": round(pm25 / WHO_GUIDELINE_PM25, 1),
    }
