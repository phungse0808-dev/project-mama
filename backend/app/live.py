"""ดึงค่าฝุ่นสดจาก Air4Thai เองเมื่อข้อมูลในฐานข้อมูลเก่าเกินไป

ทำไมต้องมี
    ระบบเก็บข้อมูลสองทาง ทางหนึ่งคือบอทบน GitHub Actions ที่เก็บเป็นไฟล์ CSV
    อีกทางคือนำไฟล์เหล่านั้นเข้าฐานข้อมูลในเครื่อง สองขั้นนี้แยกกัน
    ถ้าไม่ได้สั่งนำเข้า หน้าเว็บจะค้างอยู่ที่ชั่วโมงเก่าทั้งที่ไฟล์ใหม่มาถึงแล้ว

    โมดูลนี้ปิดช่องว่างนั้น เมื่อมีคนเปิดหน้าเว็บและพบว่าข้อมูลเก่าเกินกำหนด
    ระบบจะไปดึงจาก Air4Thai เองทันทีแล้วบันทึกลงฐานข้อมูล
    หน้าเว็บจึงแสดงชั่วโมงล่าสุดที่ต้นทางมีเสมอ โดยไม่ต้องรอให้ใครมาสั่งนำเข้า

    ยังคงเก็บลงฐานข้อมูลเหมือนเดิม ไม่ได้ดึงมาแสดงแล้วทิ้ง
    เพราะข้อมูลย้อนหลังคือหัวใจของงานวิจัย ห้ามหายแม้แต่ชั่วโมงเดียว

ข้อจำกัดที่แก้ไม่ได้
    Air4Thai เผยแพร่ค่าเป็นรายชั่วโมง ค่าที่ได้จึงเป็นค่าเฉลี่ยของชั่วโมงนั้น
    ไม่ใช่ค่า ณ วินาทีที่เปิดหน้าเว็บ ต่อให้ดึงถี่แค่ไหนก็ไม่มีค่าที่ละเอียดกว่านี้
    สิ่งที่ทำได้คือไม่ให้ช้ากว่าที่ต้นทางมี และบอกให้ผู้ใช้รู้ว่าข้อมูลเก่ากี่นาที
"""

import logging
import time
from datetime import datetime, timedelta

from sqlmodel import Session, func, select

from app.models import Reading

logger = logging.getLogger(__name__)

# ข้อมูลเก่ากว่านี้ถือว่าควรไปถามต้นทางใหม่
#
# ตั้งไว้เกินหนึ่งชั่วโมงเล็กน้อยโดยตั้งใจ เพราะต้นทางออกข้อมูลเป็นรายชั่วโมง
# และมักออกช้ากว่าเวลาที่ระบุอยู่หลายสิบนาที ถ้าตั้งสั้นกว่านี้จะไปถามซ้ำ
# ทั้งที่รู้อยู่แล้วว่ายังไม่มีอะไรใหม่
STALE_MINUTES = 70

# เว้นระยะขั้นต่ำระหว่างการไปถามต้นทางสองครั้ง
#
# จำเป็นเพราะเมื่อต้นทางยังไม่ออกข้อมูลชั่วโมงใหม่ ข้อมูลในฐานข้อมูลก็ยังเก่าอยู่
# ถ้าไม่มีตัวคุมนี้ ทุกครั้งที่มีคนเปิดหน้าเว็บจะยิงไปที่ต้นทางหนึ่งครั้ง
# กลายเป็นถล่มเซิร์ฟเวอร์ของกรมควบคุมมลพิษโดยไม่ได้ตั้งใจ
RETRY_MINUTES = 10

_last_attempt: float = 0.0


def latest_measured_at(session: Session) -> datetime | None:
    """เวลาของค่าตรวจวัดล่าสุดที่มีในฐานข้อมูล"""
    return session.exec(select(func.max(Reading.measured_at))).one()


def minutes_behind(measured_at: datetime | None) -> int | None:
    """ข้อมูลชุดนี้เก่ากว่าเวลาปัจจุบันกี่นาที ใช้บอกผู้ใช้ว่าข้อมูลสดแค่ไหน"""
    if measured_at is None:
        return None
    return max(0, int((datetime.now() - measured_at).total_seconds() // 60))


def refresh_if_stale(session: Session) -> bool:
    """ไปดึงจาก Air4Thai ถ้าข้อมูลเก่าเกินกำหนดและเว้นระยะจากครั้งก่อนพอแล้ว

    คืน True เมื่อได้ค่าตรวจวัดใหม่เพิ่มเข้ามาจริง

    กลืนข้อผิดพลาดทั้งหมดโดยตั้งใจ เพราะนี่เป็นการเสริมให้ข้อมูลสดขึ้นเท่านั้น
    ถ้าต้นทางล่มหรือเน็ตไม่ติด หน้าเว็บต้องยังแสดงข้อมูลเท่าที่มีในฐานข้อมูลได้
    ไม่ใช่ขึ้นหน้าจอแดงทั้งหน้า
    """
    global _last_attempt

    newest = latest_measured_at(session)
    if newest is not None and newest > datetime.now() - timedelta(minutes=STALE_MINUTES):
        return False

    if time.monotonic() - _last_attempt < RETRY_MINUTES * 60:
        return False

    _last_attempt = time.monotonic()

    # นำเข้าตรงนี้แทนที่จะไว้บนสุดของไฟล์ เพื่อตัดวงจรการอ้างถึงกันไปมา
    # ระหว่าง air4thai กับโมดูลนี้
    from app.air4thai import collect

    try:
        log = collect(session)
    except Exception:
        logger.warning("ดึงข้อมูลสดจาก Air4Thai ไม่สำเร็จ ใช้ข้อมูลเดิมที่มีอยู่", exc_info=True)
        return False

    if log.records_new:
        logger.info("ดึงข้อมูลสดได้ค่าใหม่ %s รายการ", log.records_new)
    return bool(log.records_new)
