/** สีตัวหนังสือของแต่ละระดับคุณภาพอากาศ สำหรับใช้บนพื้นขาว
 *
 * ทำไมต้องมีสีชุดที่สอง
 *     สีห้าระดับที่กรมควบคุมมลพิษกำหนดไว้ ออกแบบมาให้ใช้ระบายพื้น ไม่ได้ออกแบบมาเป็นตัวหนังสือ
 *     พอเอามาเป็นสีตัวอักษรบนพื้นขาว ความต่างของสีไม่ถึงเกณฑ์ 4.5:1 ที่ตัวอักษรต้องผ่าน
 *
 *         ดีมาก          #0099ff   3.00:1
 *         ดี             #00b050   2.87:1
 *         ปานกลาง        #ffd400   1.43:1   อ่านไม่ออกเลย
 *         เริ่มมีผลกระทบ  #ff7e00   2.55:1
 *         มีผลกระทบ      #ff0000   4.00:1
 *
 *     เฉดในตารางข้างล่างคือสีเดิมที่ลดความสว่างลงจนพอดีเกณฑ์ โดยคุมเนื้อสีไว้เท่าเดิม
 *     ส้มยังเป็นส้ม เหลืองยังเป็นเหลือง แค่เข้มขึ้น ทุกค่าวัดได้ 4.5:1 ขึ้นไปบนพื้นขาว
 *
 * ใช้กับอะไร
 *     เฉพาะตอนที่เอาสีระดับไปเป็น "ตัวหนังสือ" เท่านั้น
 *     ส่วนที่ระบายพื้น เช่น แท่งกราฟ จุดสี และรูปจังหวัดบนแผนที่ ยังใช้สีมาตรฐานเดิมทุกสี
 *     เพราะพื้นสีไม่ได้อยู่ใต้เกณฑ์เดียวกับตัวอักษร และแก้ด้วยการเติมเส้นขอบแทนแล้ว
 */
const INK: Record<string, string> = {
  "#0099ff": "#0072bf",
  "#00b050": "#00813b",
  "#ffd400": "#887100",
  "#ff7e00": "#b15700",
  "#ff0000": "#da0000",
};

/** แปลงสีพื้นของระดับเป็นสีตัวหนังสือ
 *
 * สีที่ไม่รู้จักคืนค่าเดิมไป ไม่ใช่คืนสีเข้มมั่ว ๆ
 * เพราะถ้าวันหนึ่งต้นทางเพิ่มระดับใหม่ ควรเห็นสีจริงที่ส่งมาแล้วรู้ว่าต้องมาเติมตารางนี้
 * ดีกว่าให้กลายเป็นสีอื่นเงียบ ๆ โดยไม่มีใครรู้
 */
export function levelInk(color: string | undefined): string | undefined {
  if (!color) return undefined;
  return INK[color.toLowerCase()] ?? color;
}
