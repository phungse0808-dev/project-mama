/**
 * ไอคอนสภาพอากาศ วาดจากรหัสมาตรฐาน WMO ที่ต้นทางส่งมา
 *
 * ทำไมต้องมี
 *     คำอธิบายเป็นตัวหนังสือต้องอ่านก่อนถึงจะรู้ว่าอากาศเป็นอย่างไร
 *     ภาพบอกได้ทันทีตั้งแต่กวาดสายตา ซึ่งเป็นสิ่งที่การ์ดสรุปควรทำ
 *
 * ทำไมวาดเองเป็น SVG แทนที่จะโหลดรูปจากที่อื่น
 *     โปรเจกต์ต้องเปิดได้แม้ไม่มีอินเทอร์เน็ต และรูปต้องไม่หายถ้าเว็บต้นทางปิดตัว
 *     SVG ยังคมทุกขนาดหน้าจอ ต่างจากไฟล์ภาพที่ต้องเตรียมหลายความละเอียด
 *
 * เลือกภาพจากรหัสจริงที่ต้นทางส่งมา ไม่ได้เดาจากอุณหภูมิหรือคำอธิบาย
 * เพราะการเดาจะผิดในกรณีที่พบบ่อย เช่น ฝนตกตอนอากาศร้อน
 */

type Props = {
  code: number | null | undefined;
  size?: number;
};

const SUN = "#f5c04a";
const CLOUD_DARK = "#b9c6d6";
const CLOUD_LIGHT = "#d5dfeb";
const RAIN = "#3d8fd8";

/** เมฆก้อนหน้า ใช้ซ้ำในหลายสภาพอากาศ */
const cloudFront = (fill: string) => (
  <path
    d="M17 34c-3.5 0-6.3-2.7-6.3-6 0-3.1 2.4-5.6 5.6-5.9C17.5 18.4 20.5 16 24.1 16c4.3 0 7.7 3.2 8 7.3 3 .2 5.4 2.7 5.4 5.6 0 3.1-2.6 5.6-5.8 5.6H17z"
    fill={fill}
  />
);

export function WeatherIcon({ code, size = 46 }: Props) {
  const common = {
    viewBox: "0 0 48 48",
    width: size,
    height: size,
    "aria-hidden": true as const,
    style: { flex: "none" as const },
  };

  const value = code ?? -1;

  // ท้องฟ้าแจ่มใสและมีเมฆบางส่วน (รหัส 0 กับ 1)
  if (value === 0 || value === 1) {
    return (
      <svg {...common}>
        <circle cx="24" cy="24" r="10" fill={SUN} />
        <g stroke={SUN} strokeWidth="3" strokeLinecap="round">
          <line x1="24" y1="5" x2="24" y2="10" />
          <line x1="24" y1="38" x2="24" y2="43" />
          <line x1="5" y1="24" x2="10" y2="24" />
          <line x1="38" y1="24" x2="43" y2="24" />
          <line x1="11" y1="11" x2="14.5" y2="14.5" />
          <line x1="33.5" y1="33.5" x2="37" y2="37" />
          <line x1="37" y1="11" x2="33.5" y2="14.5" />
          <line x1="14.5" y1="33.5" x2="11" y2="37" />
        </g>
      </svg>
    );
  }

  // มีเมฆเป็นส่วนมาก ยังเห็นดวงอาทิตย์อยู่ (รหัส 2)
  if (value === 2) {
    return (
      <svg {...common}>
        <circle cx="18" cy="17" r="8" fill={SUN} />
        {cloudFront(CLOUD_LIGHT)}
      </svg>
    );
  }

  // เมฆครึ้ม ไม่เห็นดวงอาทิตย์ ใช้เมฆสองชั้นให้ดูหนากว่ารหัส 2 (รหัส 3)
  if (value === 3) {
    return (
      <svg {...common}>
        <path
          d="M14 32c-4.4 0-8-3.4-8-7.6 0-3.9 3.1-7.1 7.1-7.5C14.6 13 18.4 10 23 10c5.4 0 9.8 4.1 10.2 9.3 3.8.3 6.8 3.4 6.8 7.1 0 3.9-3.3 7.1-7.4 7.1H14z"
          fill={CLOUD_DARK}
        />
        {cloudFront(CLOUD_LIGHT)}
      </svg>
    );
  }

  // หมอกและหมอกน้ำค้างแข็ง (รหัส 45, 48)
  if (value === 45 || value === 48) {
    return (
      <svg {...common}>
        <path d="M8 20c0-1.1.9-2 2-2h28a2 2 0 010 4H10a2 2 0 01-2-2z" fill="#c3ccd8" />
        <path d="M8 28c0-1.1.9-2 2-2h24a2 2 0 010 4H10a2 2 0 01-2-2z" fill="#c3ccd8" />
        <path d="M12 36c0-1.1.9-2 2-2h20a2 2 0 010 4H14a2 2 0 01-2-2z" fill={CLOUD_LIGHT} />
      </svg>
    );
  }

  // พายุฝนฟ้าคะนอง (รหัส 95 ถึง 99)
  if (value >= 95) {
    return (
      <svg {...common}>
        <path
          d="M14 28c-4.4 0-8-3.4-8-7.6 0-3.9 3.1-7.1 7.1-7.5C14.6 9 18.4 6 23 6c5.4 0 9.8 4.1 10.2 9.3 3.8.3 6.8 3.4 6.8 7.1 0 3.9-3.3 7.1-7.4 7.1H14z"
          fill="#8d9cae"
        />
        <path d="M25 30l-9 10h7l-3 9 11-12h-7z" fill="#e5a91f" />
      </svg>
    );
  }

  // ฝนทุกชนิดตั้งแต่ฝนละอองถึงฝนซู่หนัก และหิมะซึ่งไม่เกิดในไทยแต่กันไว้
  // (รหัส 51 ถึง 86) เม็ดฝนสามเส้นเท่ากันทุกความแรง
  // เพราะขนาดไอคอนเล็กเกินกว่าจะแยกความแรงด้วยภาพได้ชัด
  // ความแรงอ่านได้จากคำอธิบายที่อยู่ข้างๆ อยู่แล้ว
  if (value >= 51 && value <= 86) {
    return (
      <svg {...common}>
        <path
          d="M14 30c-4.4 0-8-3.4-8-7.6 0-3.9 3.1-7.1 7.1-7.5C14.6 11 18.4 8 23 8c5.4 0 9.8 4.1 10.2 9.3 3.8.3 6.8 3.4 6.8 7.1 0 3.9-3.3 7.1-7.4 7.1H14z"
          fill={CLOUD_DARK}
        />
        <g stroke={RAIN} strokeWidth="3" strokeLinecap="round">
          <line x1="16" y1="35" x2="14" y2="42" />
          <line x1="24" y1="35" x2="22" y2="42" />
          <line x1="32" y1="35" x2="30" y2="42" />
        </g>
      </svg>
    );
  }

  // รหัสที่ไม่รู้จักหรือไม่มีข้อมูล ใช้เมฆกลางๆ แทนการไม่แสดงอะไรเลย
  // เพราะช่องว่างจะทำให้การ์ดเสียรูปและดูเหมือนโหลดไม่สำเร็จ
  return <svg {...common}>{cloudFront(CLOUD_LIGHT)}</svg>;
}
