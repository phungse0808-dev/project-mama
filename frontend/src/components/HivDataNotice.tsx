import { useEffect, useState } from "react";
import { api } from "../api";
import type { HivStatistics } from "../api";

/**
 * กล่องแจ้งข้อจำกัดของข้อมูล วางไว้บนสุดของหน้า HIV
 *
 * ทำไมต้องอยู่บนสุด
 *     แต่ละแผงมีคำกำกับข้อจำกัดของตัวเองอยู่แล้ว แต่อยู่ท้ายกล่องและตัวเล็ก
 *     ผู้อ่านจึงเห็นหลังจากอ่านตัวเลขและตีความไปเรียบร้อยแล้ว ซึ่งสายเกินไป
 *     ข้อจำกัดที่กระทบการตีความทุกตัวเลขในหน้านี้ต้องอ่านก่อน ไม่ใช่อ่านทีหลัง
 *
 * สามข้อที่เขียนไว้เป็นข้อที่ผู้ตรวจงานถามแน่นอน การเขียนกำกับเองตั้งแต่ต้น
 * ต่างจากการถูกจับได้ทีหลัง เพราะแสดงว่าเรารู้ข้อจำกัดของข้อมูลที่ใช้
 */
export function HivDataNotice() {
  const [data, setData] = useState<HivStatistics | null>(null);

  useEffect(() => {
    let cancelled = false;
    void (async () => {
      try {
        const result = await api.hiv();
        if (!cancelled) setData(result);
      } catch {
        if (!cancelled) setData(null);
      }
    })();
    return () => {
      cancelled = true;
    };
  }, []);

  if (!data || data.provinces.length === 0) return null;

  const covered = data.provinces.length;
  const missing = 77 - covered;

  return (
    <section className="panel notice">
      <h2 className="panel-title">
        ข้อจำกัดของข้อมูลในหน้านี้
        <span className="panel-hint">อ่านก่อนตีความตัวเลข</span>
      </h2>

      <ol className="notice-list">
        <li>
          <strong>ครอบคลุม {covered} จังหวัด ขาดอีก {missing} จังหวัด</strong>
          <p>
            แหล่งข้อมูลเผยแพร่เฉพาะจังหวัดที่มีผู้ติดเชื้อสูงสุด ไม่ใช่การสุ่มตัวอย่าง
            ตัวเลขในหน้านี้จึงเทียบกันได้เฉพาะภายใน {covered} จังหวัดนี้เท่านั้น
            จังหวัดที่ไม่อยู่ในรายการ <strong>ไม่ได้แปลว่ามีผู้ติดเชื้อน้อย</strong>{" "}
            แต่แปลว่าไม่มีข้อมูลเผยแพร่
          </p>
        </li>

        <li>
          <strong>แหล่งข้อมูลเป็นทุติยภูมิ</strong>
          <p>
            {data.source}
            <br />
            ตัวเลขต้นทางมาจากกรมควบคุมโรค แต่เราเข้าถึงผ่านสื่อที่นำมารายงานต่อ
            ไม่ได้ดึงจากระบบของหน่วยงานโดยตรง เพราะยังไม่มีช่องทางให้ดึงข้อมูลรายจังหวัดแบบเปิด
            ก่อนส่งเล่มควรหาเอกสารต้นทางมาอ้างอิงแทน
          </p>
        </li>

        <li>
          <strong>มีข้อมูลปีเดียว ({data.year})</strong>
          <p>
            บอกได้ว่าตอนนี้จังหวัดใดมีสัดส่วนผู้ติดเชื้อสูง แต่บอกแนวโน้มไม่ได้
            ว่าเพิ่มขึ้นหรือลดลง เพราะไม่มีข้อมูลปีก่อนหน้ามาเทียบ
          </p>
        </li>
      </ol>

      <p className="notice-foot">
        ข้อจำกัดเหล่านี้ไม่ได้ทำให้ข้อมูลใช้ไม่ได้ แต่กำหนดว่าใช้ตอบอะไรได้บ้าง
        หน้านี้ใช้จัดลำดับความสำคัญในการเฝ้าระวังภายในกลุ่มจังหวัดที่มีข้อมูล
        ไม่ใช่การประเมินความชุกของทั้งประเทศ
      </p>
    </section>
  );
}
